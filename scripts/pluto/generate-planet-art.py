"""Generate the ASCII Pluto drawn behind the viewer.

Shaded sphere lit from the upper left, with the Tombaugh Regio heart and a
sparse starfield. Writes planetArt.ts; pass --preview to print the art instead.

    python3 scripts/pluto/generate-planet-art.py [--preview]
"""
import math
import pathlib
import sys

ROWS, COLS = 50, 110       # glyphs are ~2:1 tall, so COLS ~= 2 * ROWS keeps the disc round
RADIUS = 0.86              # disc radius as a fraction of the frame
RAMP = " .:-=+*#%@"        # dark -> bright
LIGHT = (-0.55, -0.45, 0.70)

OUT = (pathlib.Path(__file__).resolve().parents[2]
       / "packages/electron/src/renderer/components/PlutoBackdrop/planetArt.ts")


def _norm(v):
    n = math.sqrt(sum(c * c for c in v))
    return tuple(c / n for c in v)


def _hash(a, b):
    return (math.sin(a * 12.9898 + b * 78.233) * 43758.5453) % 1.0


def _terrain(x, y):
    return (0.5 + 0.25 * math.sin(x * 7.1 + y * 3.3)
            + 0.15 * math.sin(-x * 4.7 + y * 9.2 + 1.3)
            + 0.10 * math.sin(x * 15.3 - y * 13.1))


def _in_heart(u, v):
    x, y = u * 1.2, -v * 1.2 + 0.2
    return (x * x + y * y - 1) ** 3 - x * x * y ** 3 < 0


def render():
    lx, ly, lz = _norm(LIGHT)
    rows = []
    for r in range(ROWS):
        line = []
        for c in range(COLS):
            x = ((c + 0.5) / COLS * 2 - 1) / RADIUS
            y = ((r + 0.5) / ROWS * 2 - 1) / RADIUS
            d = x * x + y * y
            if d > 1:
                star = "." if _hash(c, r) > 0.988 else ("+" if _hash(r, c) > 0.998 else " ")
                line.append(star)
                continue
            z = math.sqrt(1 - d)
            s = max(0.0, x * lx + y * ly + z * lz)
            s *= 0.75 + 0.35 * _terrain(x, y)
            if _in_heart((x - 0.25) / 0.45, (y - 0.10) / 0.45):
                s = min(1.0, s * 1.25 + 0.18)
            s = max(s, 0.06)  # faint night side so the full disc reads
            line.append(RAMP[min(len(RAMP) - 1, int(s * (len(RAMP) - 1) + 0.5))])
        rows.append("".join(line).rstrip())
    return "\n".join(rows)


def main():
    art = render()
    if "--preview" in sys.argv:
        print(art)
        return
    escaped = art.replace("\\", "\\\\").replace("`", "\\`").replace("${", "\\${")
    OUT.write_text(
        "// Generated by scripts/pluto/generate-planet-art.py -- edit the script, not this file.\n"
        f"export const PLANET_ROWS = {ROWS};\n"
        f"export const PLANET_COLS = {COLS};\n"
        f"export const PLANET_ART = `{escaped}`;\n"
    )
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
